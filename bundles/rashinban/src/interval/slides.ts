/** Create one shuffled cycle per browser source, without mutating the catalog. */
export function shuffledIntervalSlides(random: () => number = Math.random) {
  const slides = [...INTERVAL_SLIDES];
  for (let index = slides.length - 1; index > 0; index--) {
    const other = Math.floor(random() * (index + 1));
    [slides[index], slides[other]] = [slides[other], slides[index]];
  }
  return slides;
}

